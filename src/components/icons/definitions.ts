// Definiciones de los íconos como datos: capas dibujadas de atrás hacia adelante sobre un lienzo de 48×48.
//
// Relleno (`f`) y trazo (`s`):
//   'navy'    degradado vertical de la paleta (claro arriba → oscuro abajo)
//   'navy/r'  degradado radial (luz arriba a la izquierda)
//   'navy/d'  degradado diagonal
//   'navy.l'  color sólido claro · 'navy.d' color sólido oscuro
//   '#RRGGBB' color literal · 'none' sin relleno
import { HIGHLIGHT } from './tokens';

type Common = { f?: string; o?: number; s?: string; sw?: number; rot?: [number, number, number] };
export type Layer =
  | ({ t: 'p'; d: string } & Common)
  | ({ t: 'r'; x: number; y: number; w: number; h: number; rx?: number } & Common)
  | ({ t: 'c'; cx: number; cy: number; r: number } & Common)
  | ({ t: 'e'; cx: number; cy: number; rx: number; ry: number } & Common);

export type IconDef = { layers: Layer[]; ground?: boolean };

const p = (d: string, f: string, x: Common = {}): Layer => ({ t: 'p', d, f, ...x });
const r = (x: number, y: number, w: number, h: number, rx: number, f: string, c: Common = {}): Layer => ({ t: 'r', x, y, w, h, rx, f, ...c });
const c = (cx: number, cy: number, rad: number, f: string, x: Common = {}): Layer => ({ t: 'c', cx, cy, r: rad, f, ...x });
const e = (cx: number, cy: number, rx: number, ry: number, f: string, x: Common = {}): Layer => ({ t: 'e', cx, cy, rx, ry, f, ...x });
/** Línea de detalle o brillo (solo trazo). */
const l = (d: string, s: string, sw = 1.6, x: Common = {}): Layer => ({ t: 'p', d, f: 'none', s, sw, ...x });
/** Brillo blanco semitransparente. */
const hi = (d: string, sw = 2, o = 0.5): Layer => l(d, HIGHLIGHT, sw, { o });

