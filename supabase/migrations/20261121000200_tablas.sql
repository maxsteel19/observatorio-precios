-- =====================================================================
-- Observatorio de Precios PAC · Migración 2: tablas, relaciones y restricciones
-- =====================================================================

-- Perfil de cada cuenta del personal (las credenciales viven en auth.users, gestionadas por Supabase Auth).
-- Los ciudadanos no tienen cuenta: usan la app de forma anónima.
create table public.perfiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nombre text not null check (char_length(btrim(nombre)) between 2 and 120),
  email text not null unique check (email = lower(email) and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  rol public.rol_usuario not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);
comment on table public.perfiles is 'Cuentas del personal: administradores, fiscalizadores y comerciantes.';

create table public.categorias (
  id text primary key check (id ~ '^[a-z_]+$'),
  nombre text not null unique
);
comment on table public.categorias is 'Categorías del catálogo municipal (abarrotes, lácteos, etc.).';

create table public.productos (
  id text primary key check (id ~ '^[a-z0-9_-]+$'),
  nombre text not null check (char_length(btrim(nombre)) between 2 and 120),
  unidad text not null check (char_length(btrim(unidad)) between 1 and 20),
  categoria_id text not null references public.categorias (id) on update cascade on delete restrict,
  marca text check (marca is null or char_length(marca) <= 60),
  palabras_clave text[] not null default '{}',
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint productos_nombre_unidad_key unique (nombre, unidad)
);
comment on table public.productos is 'Catálogo municipal: solo se pueden registrar precios de estos productos.';

-- Un comercio (empresa) puede tener varias sucursales y, opcionalmente, una cuenta de comerciante dueña.
create table public.comercios (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(btrim(nombre)) between 2 and 120),
  rut_empresa text unique check (rut_empresa is null or public.es_rut_valido(rut_empresa)),
  tipo public.tipo_comercio not null,
  propietario_id uuid references public.perfiles (id) on delete set null,
  creado_en timestamptz not null default now()
);
comment on table public.comercios is 'Comercios de la comuna. propietario_id es la cuenta de comerciante que los administra.';

create table public.sucursales (
  id bigint generated by default as identity primary key,
  comercio_id bigint not null references public.comercios (id) on delete restrict,
  nombre_sucursal text check (nombre_sucursal is null or char_length(btrim(nombre_sucursal)) between 2 and 80),
  direccion text not null check (char_length(btrim(direccion)) between 3 and 160),
  horario text not null default '' check (char_length(horario) <= 120),
  telefono text check (telefono is null or telefono ~ '^\+?[0-9 ]{8,16}$'),
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  -- Posición del pin en el mapa ilustrado de la app (porcentaje 0–100).
  mapa_x smallint not null default 50 check (mapa_x between 0 and 100),
  mapa_y smallint not null default 50 check (mapa_y between 0 and 100),
  beneficio_tarjeta_vecina text check (beneficio_tarjeta_vecina is null or char_length(beneficio_tarjeta_vecina) <= 120),
  activa boolean not null default true,
  creado_en timestamptz not null default now()
);
comment on table public.sucursales is 'Puntos de venta donde se registran precios.';

-- Visita de un fiscalizador a una sucursal (captura OCR de la pizarra o ingreso manual).
create table public.capturas (
  id bigint generated by default as identity primary key,
  sucursal_id bigint not null references public.sucursales (id) on delete restrict,
  fiscalizador_id uuid references public.perfiles (id) on delete set null default auth.uid(),
  modo public.modo_captura not null,
  creado_en timestamptz not null default now()
);
comment on table public.capturas is 'Capturas de precios hechas por fiscalizadores; sus precios apuntan a la captura.';

-- Historial completo de precios: cada registro es una observación; nunca se sobrescribe.
-- El precio vigente de un producto en una sucursal es el registro más reciente (vista precios_vigentes).
create table public.precios (
  id bigint generated by default as identity primary key,
  producto_id text not null references public.productos (id) on update cascade on delete restrict,
  sucursal_id bigint not null references public.sucursales (id) on delete restrict,
  precio integer not null check (precio > 0 and precio <= 10000000),
  es_oferta boolean not null default false,
  oferta_hasta date,
  fuente public.fuente_precio not null,
  captura_id bigint references public.capturas (id) on delete set null,
  registrado_por uuid references public.perfiles (id) on delete set null default auth.uid(),
  registrado_en timestamptz not null default now(),
  constraint precios_oferta_hasta_solo_en_oferta check (oferta_hasta is null or es_oferta)
);
comment on table public.precios is 'Historial de precios por producto y sucursal (uno por observación).';

-- Reportes de precios incorrectos enviados por ciudadanos (sin cuenta).
create table public.reportes (
  id bigint generated by default as identity primary key,
  sucursal_id bigint not null references public.sucursales (id) on delete restrict,
  motivo text not null check (char_length(btrim(motivo)) between 3 and 80),
  comentario text not null default '' check (char_length(comentario) <= 500),
  estado public.estado_reporte not null default 'pendiente',
  creado_en timestamptz not null default now()
);
comment on table public.reportes is 'Reportes ciudadanos de precios incorrectos.';

-- Solicitud de alta de un comerciante. La cuenta queda inactiva hasta que un administrador la aprueba.
create table public.solicitudes_comerciante (
  id bigint generated by default as identity primary key,
  usuario_id uuid unique references public.perfiles (id) on delete cascade,
  comercio text not null check (char_length(btrim(comercio)) between 2 and 120),
  rut_empresa text not null check (public.es_rut_valido(rut_empresa)),
  tipo public.tipo_comercio not null,
  telefono text not null check (telefono ~ '^\+?[0-9 ]{8,16}$'),
  nombre text not null check (char_length(btrim(nombre)) between 2 and 120),
  email text not null check (email = lower(email) and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  rut text not null check (public.es_rut_valido(rut)),
  estado public.estado_solicitud not null default 'pendiente',
  creado_en timestamptz not null default now(),
  revisado_por uuid references public.perfiles (id) on delete set null,
  revisado_en timestamptz,
  constraint solicitudes_revision_completa check (
    (estado = 'pendiente' and revisado_en is null) or (estado <> 'pendiente' and revisado_en is not null)
  )
);
comment on table public.solicitudes_comerciante is 'Solicitudes de registro de comerciantes, aprobadas o rechazadas por un administrador.';

-- Log de auditoría: lo llenan triggers; nadie puede escribirlo directamente.
create table public.auditoria (
  id bigint generated always as identity primary key,
  fecha timestamptz not null default now(),
  usuario_id uuid,
  usuario_nombre text not null,
  tabla text not null,
  operacion text not null check (operacion in ('INSERT', 'UPDATE', 'DELETE')),
  registro_id text,
  detalle text not null default ''
);
comment on table public.auditoria is 'Quién cambió qué y cuándo (escrita solo por triggers).';

-- Registro de actividad de la app (monitoreo): tiempos de cada operación y errores.
create table public.eventos_app (
  id bigint generated always as identity primary key,
  fecha timestamptz not null default now(),
  nivel text not null check (nivel in ('info', 'warn', 'error')),
  operacion text not null check (char_length(operacion) between 1 and 60),
  duracion_ms integer check (duracion_ms between 0 and 600000),
  mensaje text check (char_length(mensaje) <= 500),
  plataforma text check (plataforma in ('web', 'android', 'ios')),
  version_app text check (char_length(version_app) <= 20),
  usuario_id uuid default auth.uid()
);
comment on table public.eventos_app is 'Telemetría de la app: duración de operaciones y errores informados por los clientes.';

-- Índices de las claves foráneas (Postgres no los crea solo).
create index sucursales_comercio_id_idx on public.sucursales (comercio_id);
create index comercios_propietario_id_idx on public.comercios (propietario_id);
create index productos_categoria_id_idx on public.productos (categoria_id);
create index capturas_sucursal_id_idx on public.capturas (sucursal_id);
create index capturas_fiscalizador_fecha_idx on public.capturas (fiscalizador_id, creado_en desc);
create index precios_captura_id_idx on public.precios (captura_id);
create index precios_registrado_por_idx on public.precios (registrado_por);
create index reportes_sucursal_id_idx on public.reportes (sucursal_id);
create index solicitudes_revisado_por_idx on public.solicitudes_comerciante (revisado_por);
create index auditoria_fecha_idx on public.auditoria (fecha desc);
create index eventos_app_fecha_idx on public.eventos_app (fecha desc);
